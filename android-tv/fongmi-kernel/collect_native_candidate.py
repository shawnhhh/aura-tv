"""Collect the exact upstream Media3 release AARs from Gradle output trees.

The upstream FongMi/media checkout can put build outputs outside module source
folders (for example under buildout). Search the whole pinned checkout, but
admit only the release archive generated by the matching Gradle module. Never
rename an arbitrary AAR to make the compatibility audit pass.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import sys

EXPECTED = {
    "mpvplayer": ("lib-mpvplayer", "mpvplayer", "lib-mpvplayer-release.aar"),
    "decoder_ffmpeg": ("lib-decoder-ffmpeg", "decoder_ffmpeg", "lib-decoder-ffmpeg-release.aar"),
}


def collect(source: Path, destination: Path):
    source = source.resolve(strict=True)
    destination = destination.resolve()
    if destination == source or source in destination.parents:
        raise ValueError("Candidate destination must be outside the upstream source checkout")
    results = {}
    # Gradle output directories can be overridden in upstream build logic.
    # A generated AAR must have the exact Gradle module release file name
    # and be inside an outputs/aar directory. No wildcard binary substitution.
    candidates = list(source.rglob("*.aar"))
    for module, (gradle_name, directory_name, name) in EXPECTED.items():
        matches = []
        for path in candidates:
            if path.name != name:
                continue
            parts = path.relative_to(source).parts
            if not any(parts[i:i+2] == ("outputs", "aar") for i in range(len(parts) - 1)):
                continue
            # Either module-local build/... or the shared buildout/... layouts
            # are legitimate, as long as the output is the exact module's AAR.
            is_module_local = len(parts) >= 3 and parts[:2] == ("libraries", directory_name)
            is_shared_output = any(part in ("buildout", "build") for part in parts)
            if is_module_local or is_shared_output:
                matches.append(path)
        if len(matches) != 1:
            matches_rel = [str(path.relative_to(source)) for path in matches]
            raise ValueError(
                f"{module}: expected exactly one generated {name}, got "
                f"{len(matches)}: {matches_rel}"
            )
        results[module] = matches[0]

    destination.mkdir(parents=True, exist_ok=True)
    manifest = []
    for module, (_, _, name) in EXPECTED.items():
        origin = results[module]
        target = destination / name
        shutil.copyfile(origin, target)
        original_hash = hashlib.sha256(origin.read_bytes()).hexdigest()
        if hashlib.sha256(target.read_bytes()).hexdigest() != original_hash:
            raise ValueError("Copied AAR differs from original Gradle output: " + name)
        manifest.append({
            "module": module,
            "gradle_output": str(origin.relative_to(source)),
            "filename": name,
            "sha256": original_hash,
        })
    report = {
        "status": "ORIGINAL_GRADLE_OUTPUTS_COLLECTED_NOT_COMPATIBILITY_PROOF",
        "artifacts": manifest,
    }
    (destination / "collection.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n"
    )
    return report


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--source", required=True, type=Path)
    p.add_argument("--directory", required=True, type=Path)
    args = p.parse_args()
    try:
        print(json.dumps(collect(args.source, args.directory), ensure_ascii=False, indent=2))
    except (OSError, ValueError) as error:
        sys.exit("NATIVE_COLLECTION_FAILED: " + str(error))
